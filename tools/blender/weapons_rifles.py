"""Two-handed firearms: kochegar, pompa, zhuravl, hlopushka. Forward = +Y, right-hand grip centre = origin."""
import math

from mathutils import Matrix, Vector

from wpn_geo import align_z, catmull, circle_profile, line_pts, rect_profile


def rk(y, z, k=0.2):
    """Grip rake: bottom leans rearward."""
    return (y + k * z, z)


def hguard(b, pts, w=0.0072, h=0.0052, zone='iron', bv=0.0008):
    path = [(0, y, z) for y, z in catmull(pts, 5)]
    b.sweep(path, rect_profile(w, h), zone, up=lambda i, p, t: Vector((1, 0, 0)), bv=bv)


def add_shell(b, loc, axis='Y', length=0.068, r=0.0105, scale=1.0, hull='red', head='brass', segs=10):
    """12-gauge shell: brass head at -axis end, plastic hull, rolled crimp."""
    L = length * scale
    R = r * scale
    hh = 0.0165 * scale
    prof_head = [(R * 1.07, 0.0), (R * 1.07, hh * 0.25), (R * 0.97, hh * 0.35), (R, hh)]
    b.lathe([(R * 0.55, 0.0)] + prof_head + [(R, hh * 1.0)], axis, loc=loc, segs=segs, zone=head, cap=False)
    b.lathe([(R * 0.35, 0.0), (R * 0.55, 0.0)], axis, loc=loc, segs=segs, zone='steel', cap=False)
    prof_hull = [(R * 0.995, hh * 0.95), (R * 0.995, L - 0.004 * scale), (R * 0.93, L - 0.001 * scale), (R * 0.55, L)]
    b.lathe(prof_hull, axis, loc=loc, segs=segs, zone=hull, cap=True)


