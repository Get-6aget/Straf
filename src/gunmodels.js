export function buildWeaponModel(id) {
  const def = WEAPONS[id];
  const g = new THREE.Group();
  if (!def || !BUILD[id]) return g;
  const p = new Parts(def.paint);
  BUILD[id](p);
  g.add(p.build());
  return g;
}

